#!/usr/bin/env python3
"""Capture the dashboard, panel by panel, from a live run on disk.

WHAT THIS IS. The screenshots in README.md and docs/SCREENSHOTS.md are the
one part of the documentation a reader trusts without reading, and they
were taken by hand, which meant they went stale the moment a panel
changed. This script takes them from a running dashboard, clipping each
image to the element's own bounding box read from the live DOM, so a
panel image is exactly that panel and the set can be regenerated by
anyone with one command.

    python3 scripts/screenshots.py --artifacts /tmp/option-desk-demo \
        --underlying SPY --expiry 2026-10-16

It starts the dashboard from this checkout on a spare port, drives a
headless browser over it, writes the nine README images at a 1400 pixel
viewport and the gallery at 1600, and rewrites docs/SCREENSHOTS.md from
what it captured. Nothing is committed; look at the images first.

Needs Playwright and its Chromium: `pip install playwright` then
`python -m playwright install chromium`. Both are optional for the
project, which is why this is a script rather than a test.
"""

