"""Create synthetic LEAN minute data and a backtest bundle, with no data download.

CSV layout follows QuantConnect/Lean Common/Util/LeanData.cs. These quotes
are arbitrary plumbing fixtures, not prices generated by a valuation model.
"""
import json
from pathlib import Path
import sys
from zipfile import ZipFile, ZIP_DEFLATED

from evaluate import export_plan


def prepare(destination):
    destination = Path(destination)
    plan = {"underlying": "SPY", "expiry": "2016-01-15", "legs": [
        {"kind": "call", "side": "long", "qty": 1, "strike": 200, "price": 2}]}
    export_plan(plan, destination, start="2016-01-04", end="2016-01-06",
                exercise_style="american", multiplier=100, data_mode="synthetic")
    for offset, day in enumerate(("20160104", "20160105", "20160106")):
        for asset in ("equity", "option"):
            directory = destination / "data" / asset / "usa" / "minute" / "spy"
            directory.mkdir(parents=True, exist_ok=True)
            option = asset == "option"
            suffix = "quote_american" if option else "trade"
            entry = (f"{day}_spy_minute_quote_american_call_2000000_20160115.csv" if option
                     else f"{day}_spy_minute_trade.csv")
            lines = []
            for minute in range(570, 960):
                if option:
                    bid = 20000 + offset * 1000
                    fields = [minute*60000] + [bid]*4 + [10] + [bid+1000]*4 + [10]
                else:
                    fields = [minute*60000] + [2000000+offset*1000]*4 + [10000]
                lines.append(",".join(map(str, fields)))
            with ZipFile(directory / f"{day}_{suffix}.zip", "w", ZIP_DEFLATED) as archive:
                archive.writestr(entry, "\n".join(lines) + "\n")
    # Raw equity subscriptions still need an identity mapping for this fixture.
    maps = destination / "data/equity/usa/map_files"
    maps.mkdir(parents=True)
    (maps / "spy.csv").write_text("19980101,spy,usa\n20501231,spy,usa\n")
    rates = destination / "data/alternative/interest-rate/usa/interest-rate.csv"
    rates.parent.mkdir(parents=True)
    rates.write_text("date,rate\n2016-01-01,0.0\n")
    config = {
        "environment": "backtesting", "live-mode": False,
        "algorithm-type-name": "OptionDeskEvaluation", "algorithm-language": "Python",
        "algorithm-location": "/evaluation/main.py", "data-folder": "/evaluation/data",
        "results-destination-folder": "/evaluation/results", "debugging": False,
        "log-handler": "QuantConnect.Logging.CompositeLogHandler",
        "messaging-handler": "QuantConnect.Messaging.Messaging",
        "job-queue-handler": "QuantConnect.Queues.JobQueue",
        "api-handler": "QuantConnect.Api.Api",
        "map-file-provider": "QuantConnect.Data.Auxiliary.LocalDiskMapFileProvider",
        "factor-file-provider": "QuantConnect.Data.Auxiliary.LocalDiskFactorFileProvider",
        "data-provider": "QuantConnect.Lean.Engine.DataFeeds.DefaultDataProvider",
        "data-channel-provider": "DataChannelProvider",
        "object-store": "QuantConnect.Lean.Engine.Storage.LocalObjectStore",
        "data-aggregator": "QuantConnect.Lean.Engine.DataFeeds.AggregationManager",
        "setup-handler": "QuantConnect.Lean.Engine.Setup.BacktestingSetupHandler",
        "result-handler": "QuantConnect.Lean.Engine.Results.BacktestingResultHandler",
        "data-feed-handler": "QuantConnect.Lean.Engine.DataFeeds.FileSystemDataFeed",
        "real-time-handler": "QuantConnect.Lean.Engine.RealTime.BacktestingRealTimeHandler",
        "history-provider": ["QuantConnect.Lean.Engine.HistoricalData.SubscriptionDataReaderHistoryProvider"],
        "transaction-handler": "QuantConnect.Lean.Engine.TransactionHandlers.BacktestingTransactionHandler",
        "job-user-id": "0", "api-access-token": "", "job-organization-id": "",
    }
    (destination / "config.json").write_text(json.dumps(config, indent=2) + "\n")


if __name__ == "__main__":
    prepare(sys.argv[1])
